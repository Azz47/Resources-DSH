def renumber(els, idx):
    """页码只在 rband 的 rb_num 一处出现：集中改写，避免 44 处字面量错位。"""
    for e in els:
        if e.get("elementId") == "rb_num":
            c = e.get("content") or {}
            if isinstance(c, dict) and "text" in c:
                c["text"] = "%02d / %02d" % (idx, TOTAL)


def main():
    pdir = os.path.join(ROOT, "pages")
    if not os.path.isdir(pdir):
        os.makedirs(pdir)
    files = []
    for i, (fn, name, notes, bg, ptype) in enumerate(ALL, 1):
        els = []
        fn(els)
        renumber(els, i)
        page_bg = bg
        if bg == BG_PAPER:
            page_bg = PAPER_BY_SEC.get(CUR_SEC[0], bg)
        dump(os.path.join(pdir, name + ".yaml"), els, NOTES.get(name, notes), ptype, page_bg)
        files.append("pages/%s.yaml" % name)
        print("%2d %-16s %3d els" % (i, name, len(els)))
    with io.open(os.path.join(ROOT, "deck.yaml"), "w", encoding="utf8") as f:
        f.write(deck_yaml("第二单元 进入新时代 · 单元思考与行动", files))
    print("wrote %d pages + deck.yaml" % len(files))


if __name__ == "__main__":
    main()
